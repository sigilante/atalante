#!/usr/bin/env python3
"""atlc.py: the ATL corpus runner behind tools/atlc.sh.

  atlc.py corpus [CASE.atl ...]     run cases (default: tests/atl/*.atl), print a table
  atlc.py run CASE.atl              run one case, print the transcript
  atlc.py gen [CASE.atl ...]        write the generated Jock program and stop
  atlc.py lex [CASE.atl ...]        run the LEX corpus (default: tests/lex/*.atl)
  atlc.py lexcheck [CASE.atl ...]   lex every input line of the EVAL corpus; report refusals
  atlc.py parse [CASE.atl ...]      run the PARSE corpus (default: tests/parse/*.atl)

A parse case may open with `⍝ sig: n:a DIV:d` naming each name's class
for the parser (a array, m monadic, d dyadic, b ambivalent, n niladic);
every other name is unbound.

The runner turns the cases into ONE Jock program (tests/gen/corpus.jock)
that imports the `atl` module from src/ and calls atl.corpus, compiles
it with the Jock front door (JOCK env, default ~/Code/jock), and splits
the product string on the separators src/atl.jock documents. One honk
build per corpus run (~14 s), not one per case.
"""
import os, subprocess, sys, glob

# A corpus product is one atom of a few thousand bytes; as a decimal
# string that is past Python's default int<->str limit (4300 digits),
# on both sides of the JSON lane --- jockc.sh's own serializer and
# our parser. Lift it here and in the child (S-10).
sys.set_int_max_str_digits(0)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JOCK = os.environ.get("JOCK", os.path.expanduser("~/Code/jock"))
GEN = os.path.join(ROOT, "tests", "gen", f"corpus-{os.getpid()}.jock")   # per process: runs may be parallel
GS, RS, US = "\x1d", "\x1e", "\x1f"
BATCH = int(os.environ.get("ATL_BATCH", "1000"))   # cases per generated program; one program by default (S-13 closed)


CLASSES = {"a": 1, "m": 2, "d": 3, "b": 4, "n": 5}


def parse_case(path):
    """-> (name, [(input_line, [expect_lines], refuse_tag_or_None), ...], sig)"""
    name = os.path.splitext(os.path.basename(path))[0]
    steps = []
    sig = []
    for raw in open(path, encoding="utf-8").read().split("\n"):
        line = raw.rstrip("\r")
        if line.startswith("⍝ sig:"):
            for word in line[len("⍝ sig:"):].split():
                nm, _, c = word.partition(":")
                if c not in CLASSES:
                    sys.exit(f"{path}: bad class in sig directive: {word}")
                sig.append((nm, CLASSES[c]))
        elif line.startswith("⍝ expect:"):
            if not steps:
                sys.exit(f"{path}: expect before any input")
            # exactly ONE space after the colon is the separator; the rest is
            # the expected text, leading spaces included (right-aligned columns)
            rest = line[len("⍝ expect:"):]
            steps[-1][1].append(rest[1:] if rest.startswith(" ") else rest)
        elif line.startswith("⍝ refuse:"):
            if not steps:
                sys.exit(f"{path}: refuse before any input")
            steps[-1][2] = line[len("⍝ refuse:"):].strip()
        elif line.strip() == "":
            continue
        else:
            steps.append([line, [], None])
    return name, steps, sig


def jock_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("{", "{{").replace("}", "}}")
    return '"' + s + '"'


def generate(cases, entry="corpus"):
    rows = []
    for name, steps, sig in cases:
        lines = ", ".join(jock_str(st[0]) for st in steps)
        if entry == "parsecorpus":
            sigs = ", ".join(f"({jock_str(n)}, {c})" for n, c in sig)
            rows.append(f"  ({jock_str(name)}, [{sigs}], [{lines}])")
        else:
            rows.append(f"  ({jock_str(name)}, [{lines}])")
    body = ",\n".join(rows)
    return ("// GENERATED by tools/atlc.py --- do not edit.\n"
            "import atl;\n"
            f"atl.{entry}([\n{body}\n])\n")


PKGS = os.path.join(ROOT, "pkgs")


def ensure_pkg():
    """Build each package jam with tools/pkg.sh when missing or stale."""
    import hashlib
    numerics = sorted(glob.glob(os.path.join(ROOT, "vendor", "numerics", "*", "*.hoon")))
    for name in ("lagoon", "nasm"):
        jam = os.path.join(PKGS, name + ".jam")
        inputs = [os.path.join(ROOT, "pkg", name + "-core.hoon")] + numerics
        h = hashlib.sha256()
        for f in inputs:
            h.update(open(f, "rb").read())
        want = h.hexdigest()
        have = open(jam + ".sha").read().strip() if os.path.exists(jam + ".sha") else ""
        if not os.path.exists(jam) or have != want:
            sys.stderr.write(f"atlc: building the {name} package\n")
            p = subprocess.run(["zsh", os.path.join(ROOT, "tools", "pkg.sh"), name], capture_output=True, text=True)
            if p.returncode != 0:
                sys.stderr.write(p.stdout + p.stderr)
                sys.exit("atlc: package build failed")


def run_jock(gen_path):
    """Compile and run the generated program; -> the product String.

    `--diag run` answers {"status":"ok","value":<noun as nested ints>}; a
    String's erasure is its cord, so the value is one atom and the text
    is its little-endian bytes. This sidesteps the prose renderer, which
    renders a String reached through an import as a bare number."""
    import json
    ensure_pkg()
    cmd = ["zsh", os.path.join(JOCK, "tools", "jockc.sh"), "--diag",
           "--data-dir", os.path.join(ROOT, "src"), "--data-dir", PKGS, "run", gen_path]
    env = dict(os.environ, PYTHONINTMAXSTRDIGITS="0")
    p = subprocess.run(cmd, capture_output=True, text=True, env=env)
    try:
        rec = json.loads(p.stdout.strip().splitlines()[-1])
    except (ValueError, IndexError):
        sys.stderr.write(p.stdout + p.stderr)
        sys.exit(f"atlc: no JSON record from jock (exit {p.returncode})")
    if rec.get("status") != "ok":
        sys.stderr.write(json.dumps(rec, indent=1, ensure_ascii=False) + "\n")
        sys.exit("atlc: jock refused or crashed")
    v = rec["value"]
    if not isinstance(v, int):
        sys.exit(f"atlc: product is not an atom: {str(v)[:80]}")
    return v.to_bytes((v.bit_length() + 7) // 8, "little").decode("utf-8")


def split_product(prod):
    got = {}
    for chunk in prod.split(GS):
        if not chunk:
            continue
        name, _, rest = chunk.partition(US)
        got[name] = rest.split(RS) if rest != "" else [""]
    return got


def check(steps, outputs):
    """-> list of (ok, input, expected_text, actual_text)"""
    res = []
    for i, (inp, expects, refuse) in enumerate(steps):
        actual = outputs[i] if i < len(outputs) else "<missing>"
        if refuse is not None:
            ok = actual.startswith(refuse)
            exp = refuse
        else:
            exp = "\n".join(expects)
            ok = actual == exp
        res.append((ok, inp, exp, actual))
    return res


def main(argv):
    if len(argv) < 2 or argv[1] not in ("corpus", "run", "gen", "lex", "lexcheck", "parse"):
        sys.exit(__doc__)
    verb = argv[1]
    subdir = {"lex": "lex", "parse": "parse"}.get(verb, "atl")
    files = argv[2:] or sorted(glob.glob(os.path.join(ROOT, "tests", subdir, "*.atl")))
    if verb == "run" and len(files) != 1:
        sys.exit("atlc run: exactly one case")
    cases = [parse_case(f) for f in files]
    os.makedirs(os.path.dirname(GEN), exist_ok=True)
    entry = {"lex": "lexcorpus", "lexcheck": "lexcorpus", "parse": "parsecorpus"}.get(verb, "corpus")
    if verb == "gen":
        gen = os.path.join(ROOT, "tests", "gen", "corpus.jock")
        with open(gen, "w", encoding="utf-8") as f:
            f.write(generate(cases, entry))
        print(gen)
        return 0
    # one program per BATCH of cases;  the default is one program for the
    # whole corpus (~3 min).  ATL_BATCH splits it, which S-13 once needed
    got = {}
    for i in range(0, len(cases), BATCH):
        part = cases[i:i + BATCH]
        with open(GEN, "w", encoding="utf-8") as f:
            f.write(generate(part, entry))
        got.update(split_product(run_jock(GEN)))
    try:
        os.remove(GEN)
    except OSError:
        pass
    if verb == "lexcheck":
        bad = 0
        for name, steps, _sig in cases:
            outs = got.get(name, [])
            for i, (inp, _e, _r) in enumerate(steps):
                out = outs[i] if i < len(outs) else "<missing>"
                if out.startswith("%") or out == "<missing>":
                    bad += 1
                    print(f"{name}: {inp}\n      {out}")
        nlines = sum(len(st) for _n, st, _s in cases)
        print(f"lexcheck: {nlines - bad}/{nlines} lines tokenize, {bad} refused")
        return 0 if bad == 0 else 1
    total_pass = total = 0
    failed_cases = 0
    for name, steps, _sig in cases:
        res = check(steps, got.get(name, []))
        npass = sum(1 for r in res if r[0])
        total_pass += npass
        total += len(res)
        if npass != len(res):
            failed_cases += 1
        if verb == "run":
            for ok, inp, exp, act in res:
                mark = "ok  " if ok else "FAIL"
                print(f"{mark}  {inp}")
                if ok and act != "":
                    for ln in act.split("\n"):
                        print(f"      {ln}")
                if not ok:
                    print(f"      expected: {exp!r}")
                    print(f"      actual:   {act!r}")
        else:
            status = "pass" if npass == len(res) else "FAIL"
            print(f"{name:<22} {npass:>3}/{len(res):<3} {status}")
    print(f"{'total':<22} {total_pass:>3}/{total:<3} {len(cases) - failed_cases}/{len(cases)} cases")
    return 0 if failed_cases == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
