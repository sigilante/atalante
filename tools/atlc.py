#!/usr/bin/env python3
"""atlc.py: the ATL corpus runner behind tools/atlc.sh.

  atlc.py corpus [CASE.atl ...]     run cases (default: tests/atl/*.atl), print a table
  atlc.py run CASE.atl              run one case, print the transcript
  atlc.py gen [CASE.atl ...]        write the generated Jock program and stop

The runner turns the cases into ONE Jock program (tests/gen/corpus.jock)
that imports the `atl` module from src/ and calls atl.corpus, compiles
it with the Jock front door (JOCK env, default ~/Code/jock), and splits
the product string on the separators src/atl.jock documents. One honk
build per corpus run (~14 s), not one per case.
"""
import os, subprocess, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JOCK = os.environ.get("JOCK", os.path.expanduser("~/Code/jock"))
GEN = os.path.join(ROOT, "tests", "gen", "corpus.jock")
GS, RS, US = "\x1d", "\x1e", "\x1f"


def parse_case(path):
    """-> (name, [(input_line, [expect_lines], refuse_tag_or_None), ...])"""
    name = os.path.splitext(os.path.basename(path))[0]
    steps = []
    for raw in open(path, encoding="utf-8").read().split("\n"):
        line = raw.rstrip("\r")
        if line.startswith("⍝ expect:"):
            if not steps:
                sys.exit(f"{path}: expect before any input")
            steps[-1][1].append(line[len("⍝ expect:"):].lstrip(" ") if line[len("⍝ expect:"):].strip() else "")
        elif line.startswith("⍝ refuse:"):
            if not steps:
                sys.exit(f"{path}: refuse before any input")
            steps[-1][2] = line[len("⍝ refuse:"):].strip()
        elif line.strip() == "":
            continue
        else:
            steps.append([line, [], None])
    return name, steps


def jock_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("{", "{{").replace("}", "}}")
    return '"' + s + '"'


def generate(cases):
    rows = []
    for name, steps in cases:
        lines = ", ".join(jock_str(st[0]) for st in steps)
        rows.append(f"  ({jock_str(name)}, [{lines}])")
    body = ",\n".join(rows)
    return ("// GENERATED by tools/atlc.py --- do not edit.\n"
            "import atl;\n"
            f"atl.corpus([\n{body}\n])\n")


def run_jock(gen_path):
    """Compile and run the generated program; -> the product String.

    `--diag run` answers {"status":"ok","value":<noun as nested ints>}; a
    String's erasure is its cord, so the value is one atom and the text
    is its little-endian bytes. This sidesteps the prose renderer, which
    renders a String reached through an import as a bare number."""
    import json
    cmd = ["zsh", os.path.join(JOCK, "tools", "jockc.sh"), "--diag",
           "--data-dir", os.path.join(ROOT, "src"), "run", gen_path]
    p = subprocess.run(cmd, capture_output=True, text=True)
    try:
        rec = json.loads(p.stdout.strip().splitlines()[-1])
    except (ValueError, IndexError):
        sys.stderr.write(p.stdout + p.stderr)
        sys.exit(f"atlc: no JSON record from jock (exit {p.returncode})")
    if rec.get("status") != "ok":
        sys.stderr.write(json.dumps(rec, indent=1, ensure_ascii=False) + "\n")
        sys.exit("atlc: jock refused or crashed")
    v = rec["value"]
    if not isinstance(v, int):
        sys.exit(f"atlc: product is not an atom: {str(v)[:80]}")
    return v.to_bytes((v.bit_length() + 7) // 8, "little").decode("utf-8")


def split_product(prod):
    got = {}
    for chunk in prod.split(GS):
        if not chunk:
            continue
        name, _, rest = chunk.partition(US)
        got[name] = rest.split(RS) if rest != "" else [""]
    return got


def check(steps, outputs):
    """-> list of (ok, input, expected_text, actual_text)"""
    res = []
    for i, (inp, expects, refuse) in enumerate(steps):
        actual = outputs[i] if i < len(outputs) else "<missing>"
        if refuse is not None:
            ok = actual.startswith(refuse)
            exp = refuse
        else:
            exp = "\n".join(expects)
            ok = actual == exp
        res.append((ok, inp, exp, actual))
    return res


def main(argv):
    if len(argv) < 2 or argv[1] not in ("corpus", "run", "gen"):
        sys.exit(__doc__)
    verb = argv[1]
    files = argv[2:] or sorted(glob.glob(os.path.join(ROOT, "tests", "atl", "*.atl")))
    if verb == "run" and len(files) != 1:
        sys.exit("atlc run: exactly one case")
    cases = [parse_case(f) for f in files]
    os.makedirs(os.path.dirname(GEN), exist_ok=True)
    with open(GEN, "w", encoding="utf-8") as f:
        f.write(generate(cases))
    if verb == "gen":
        print(GEN)
        return 0
    got = split_product(run_jock(GEN))
    total_pass = total = 0
    failed_cases = 0
    for name, steps in cases:
        res = check(steps, got.get(name, []))
        npass = sum(1 for r in res if r[0])
        total_pass += npass
        total += len(res)
        if npass != len(res):
            failed_cases += 1
        if verb == "run":
            for ok, inp, exp, act in res:
                mark = "ok  " if ok else "FAIL"
                print(f"{mark}  {inp}")
                if not ok:
                    print(f"      expected: {exp!r}")
                    print(f"      actual:   {act!r}")
        else:
            status = "pass" if npass == len(res) else "FAIL"
            print(f"{name:<22} {npass:>3}/{len(res):<3} {status}")
    print(f"{'total':<22} {total_pass:>3}/{total:<3} {len(cases) - failed_cases}/{len(cases)} cases")
    return 0 if failed_cases == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
